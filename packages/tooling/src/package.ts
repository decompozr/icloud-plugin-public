import {artifactSchema} from './artifact.js';
import {mkdir} from 'node:fs/promises';
import {resolve,join} from 'node:path';
const root=resolve(import.meta.dir,'../../..');
const input=resolve(process.argv[2]??join(root,'.flow-runtime','build',`${process.platform}-${process.arch}`));
const metadata=artifactSchema.parse(await Bun.file(join(input,'artifact.json')).json() as unknown);
for(const required of ['apps/icloud/dist/index.js','runtime.sh','bun.lock'])if(!await Bun.file(join(input,required)).exists())throw Error('Incomplete build artifact');
const outputDirectory=resolve(process.argv[3]??join(root,'releases'));
await mkdir(outputDirectory,{recursive:true});
const output=join(outputDirectory,`icloud-plugin-${metadata.version}-${metadata.platform}-${metadata.arch}.tar.gz`);
if(await Bun.file(output).exists())throw Error('Versioned artifact exists; refusing overwrite');
const result=Bun.spawnSync(['tar','-czf',output,'-C',input,'artifact.json','runtime.sh','package.json','bun.lock','LICENSE','THIRD_PARTY_NOTICES.md','apps','node_modules'],{stdout:'pipe',stderr:'pipe'});
if(result.exitCode!==0)throw Error('Archive creation failed');
console.log(output);
